// `partial` tools may omit keys: their generated module is an OVERRIDE layer
// merged over the engine's defaults, so writing every key would pin today's
// defaults forever and silently hold the old value the next time one moved.
function validate(schema, input, partial = false) {
  const out = {};
  const errors = [];
  for (const [key, rule] of Object.entries(schema)) {
    if (!(key in input)) {
      if (!partial) errors.push(`missing ${key}`);
      continue;
    }
    const v = input[key];
    if (rule.kind === 'number') {
      if (typeof v !== 'number' || !Number.isFinite(v)) errors.push(`${key} must be a finite number`);
      else if (v < rule.min || v > rule.max) errors.push(`${key} must be within ${rule.min}..${rule.max} (got ${v})`);
      else out[key] = v;
    } else if (rule.kind === 'boolean') {
      if (typeof v !== 'boolean') errors.push(`${key} must be a boolean`);
      else out[key] = v;
    } else if (rule.kind === 'enum') {
      if (!rule.values.includes(v)) errors.push(`${key} must be one of ${rule.values.join(', ')}`);
      else out[key] = v;
    }
  }
  const extra = Object.keys(input).filter((k) => !(k in schema));
  if (extra.length) errors.push(`unknown keys: ${extra.join(', ')}`);
  return { value: out, errors };
}

function renderModule(tool, settings) {
  const doc = tool.doc.map((line) => (line ? `// ${line}` : '//')).join('\n');
  const body = Object.entries(settings)
    .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
    .join('\n');
  return `${doc}\n\nexport const ${tool.constName} = Object.freeze({\n${body}\n});\n`;
}

// --- static file serving ----------------------------------------------------

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.md': 'text/plain; charset=utf-8',
};

async function serveStatic(req, res, pathname) {
  const rel = normalize(decodeURIComponent(pathname)).replace(/^([/\\])+/, '');
  const full = join(WEB, rel === '' ? 'index.html' : rel);
  // normalize() has already collapsed any ..; this is the belt to that braces.
  if (!full.startsWith(WEB + sep) && full !== join(WEB, 'index.html')) {
    return send(res, 403, { error: 'forbidden' });
  }
  try {
    const body = await readFile(full);
    res.writeHead(200, {
      'content-type': TYPES[extname(full)] || 'application/octet-stream',
      'cache-control': 'no-store', // this is a dev tool; never serve a stale module
    });
    res.end(body);
  } catch {
    send(res, 404, { error: `not found: /${rel}` });
  }
}

// Serve one file out of `base`, with the same traversal guard as serveStatic.
async function serveFrom(res, base, rel) {
  const full = join(base, normalize(decodeURIComponent(rel)).replace(/^([/\\])+/, ''));
  if (!full.startsWith(base + sep)) return send(res, 403, { error: 'forbidden' });
  try {
    res.writeHead(200, {
      'content-type': TYPES[extname(full)] || 'application/octet-stream',
      'cache-control': 'no-store',
    });
    res.end(await readFile(full));
  } catch {
    send(res, 404, { error: `not found: ${rel}` });
  }
}

function send(res, code, obj) {
  const body = JSON.stringify(obj);
  res.writeHead(code, { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' });
  res.end(body);
}

function readBody(req, limit = 64 * 1024) {
  return new Promise((ok, fail) => {
    let size = 0;
    const chunks = [];
    req.on('data', (c) => {
      size += c.length;
      if (size > limit) {
        fail(new Error('body too large'));
        req.destroy();
        return;
      }
      chunks.push(c);
    });
    req.on('end', () => ok(Buffer.concat(chunks).toString('utf8')));
    req.on('error', fail);
  });
}

// --- routes -----------------------------------------------------------------

async function handleApply(req, res) {
  let payload;
  try {
    payload = JSON.parse(await readBody(req));
  } catch (err) {
    return send(res, 400, { error: `bad request body: ${err.message}` });
  }

  const tool = TOOLS[payload?.tool];
  if (!tool) return send(res, 404, { error: `unknown tool: ${payload?.tool}` });
  if (!payload.settings || typeof payload.settings !== 'object') {
    return send(res, 400, { error: 'settings must be an object' });
  }

  const { value, errors } = validate(tool.schema, payload.settings, tool.partial === true);
  if (errors.length) return send(res, 422, { error: `rejected: ${errors.join('; ')}` });

  const dest = join(PROJECT, tool.path);
  const text = renderModule(tool, value);

  let previous = null;
  try {
    previous = await readFile(dest, 'utf8');
  } catch { /* first write */ }

  if (previous === text) {
    return send(res, 200, { path: tool.path, changed: false });
  }

  try {
    await mkdir(dirname(dest), { recursive: true });
    await writeFile(dest, text, 'utf8');
  } catch (err) {
    return send(res, 500, { error: `write failed: ${err.message}` });
  }

  console.log(`[apply] ${tool.path} <- ${payload.tool} (${previous === null ? 'created' : 'updated'})`);
  send(res, 200, { path: tool.path, changed: true, created: previous === null });
}

const server = createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  const path = url.pathname;

  if (path === '/api/health') {
    return send(res, 200, { ok: true, project: PROJECT, tools: Object.keys(TOOLS) });
  }

  if (path.startsWith('/api/target/')) {
    const tool = TOOLS[decodeURIComponent(path.slice('/api/target/'.length))];
    if (!tool) return send(res, 404, { error: 'unknown tool' });
    return send(res, 200, { path: tool.path, exists: existsSync(join(PROJECT, tool.path)) });
  }

  if (path === '/api/apply') {
    if (req.method !== 'POST') return send(res, 405, { error: 'POST only' });
    return handleApply(req, res);
  }

  if (req.method !== 'GET' && req.method !== 'HEAD') return send(res, 405, { error: 'GET only' });
  // Read-only engine mounts. See the ENGINE comment at the top.
  if (path.startsWith('/gamejs-raw/')) {
    return serveFrom(res, GAMEJS, path.slice('/gamejs-raw/'.length));
  }
  if (path.startsWith('/gamejs/')) {
    return serveFrom(res, GAMEJS, path.slice('/gamejs/'.length));
  }
  return serveStatic(req, res, path);
});

// Loopback only. This process writes to the working tree; it has no business
// being reachable from the network.
server.listen(PORT, '127.0.0.1', () => {
  console.log(`dev suite  http://localhost:${PORT}`);
  console.log(`project    ${PROJECT}`);
});
