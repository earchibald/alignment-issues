// Dev suite server. Node built-ins only, no dependencies.
//
//   node devtools/server.js [port]     (default 8899, or just devtools)
//
// Two jobs: serve devtools/web, and be the only thing allowed to write into the
// project tree. The browser never names a path — it names a TOOL, and the
// server decides where that tool's settings live and what shape they may take.
// A compromised or buggy page therefore cannot write anywhere it likes.

import { createServer } from 'node:http';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { extname, join, resolve, dirname, normalize, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = join(HERE, 'web');
const PROJECT = resolve(HERE, '..');
// The pacing tool simulates with the REAL engine rather than a model of it —
// a model would drift from the game and the graph would quietly become
// fiction. These two read-only mounts expose it to the browser.
//
// The mount is game/js as a WHOLE, not game/js/engine: constants.js imports
// ../config/pacing-settings.js, and a mount rooted at engine/ puts that
// outside the served tree. Mirror the real layout and relative imports keep
// working unchanged.
//
// /gamejs is the graph the simulation imports — its engine/constants.js is
// swapped for a shim by an import map. /gamejs-raw is the same tree with no
// rewriting, which is how the shim (and the tool) read the real defaults.
// Both are GET-only, like every other static path.
const GAMEJS = join(PROJECT, 'game', 'js');
const PORT = Number(process.argv[2]) || 8899;

