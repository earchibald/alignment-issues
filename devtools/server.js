// A schema entry is the whole contract: the destination, and every key with its
// type and bounds. Anything not listed is dropped, and anything out of range is
// rejected rather than clamped — a silently clamped value would be a lie about
// what you applied.

const num = (min, max) => ({ kind: 'number', min, max });
const bool = () => ({ kind: 'boolean' });
const oneOf = (...values) => ({ kind: 'enum', values });

